def range_frame_ticks(ax, x_data=None, y_data=None):
    """Drop ticks that fall outside the data range, so no tick hangs off the
    range-frame axis line (rule 4)."""
    if x_data is not None:
        lo, hi = min(x_data), max(x_data)
        ax.set_xticks([t for t in ax.get_xticks() if lo <= t <= hi])
    if y_data is not None:
        lo, hi = min(y_data), max(y_data)
        ax.set_yticks([t for t in ax.get_yticks() if lo <= t <= hi])


def tufte_axes(ax, x_data, y_data):
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["bottom"].set_bounds(min(x_data), max(x_data))
    ax.spines["left"].set_bounds(min(y_data), max(y_data))
    ax.tick_params(direction="in", length=3, width=0.5)
    range_frame_ticks(ax, x_data, y_data)


# Every chart documents its evidence: a source line and its units
# (analytical design principle 5, BE ch. 5). The showcase data are made up.
ILLUSTRATIVE = "Source: illustrative data, generated by _docs/generate_showcase.py."


def add_source(fig, text=ILLUSTRATIVE, color=None, x=0.125, y=-0.01):
    """Source line below the chart; bbox_inches='tight' keeps it in the image."""
    fig.text(x, y, text, fontsize=9, fontfamily="serif",
             color=color or C["text3"], ha="left", va="top")


